/**
 * REGRESSION TEST FOR THE UNIT GUARD.
 *
 * lib/units.ts types every across-time unit sum as `CumulativeUnits`,
 * and `formatUnits()` refuses that brand at COMPILE time -- so writing
 * `formatUnits(window.yrfi.pnl)` fails `next build` and Vercel never
 * ships it. That is the check the operator asked for: a season unit
 * total cannot be rendered, and the failure is loud rather than a
 * plausible-looking wrong number on the page.
 *
 * THIS SCRIPT GUARDS THE GUARD. The protection is one function
 * signature, and a signature is easy to loosen by accident -- widening
 * the parameter to `number` to silence an error would disable every
 * protection in the codebase and change nothing visible. So we compile
 * a probe that MUST fail, and fail this script if it succeeds.
 *
 * It also compiles the legitimate cases, because a guard that rejects
 * per-night and per-bet figures too would be quietly useless: everyone
 * would route around it and the brand would rot.
 *
 * Runs in `prebuild`, i.e. on every Vercel deploy.
 */
/* execSync with one command string, not execFileSync + shell:true --
   the latter concatenates argv without escaping and Node warns about it
   (DEP0190). There is no user input here, but a build script that
   prints a security deprecation on every deploy trains people to ignore
   build output. */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, "..");
const probePath = path.join(projectRoot, "__units_guard_probe.ts");

/* Each entry is one line of the probe plus what must happen to it.
   Line numbers are derived, never hardcoded -- a hardcoded line number
   is how this kind of test starts passing for the wrong reason. */
const CASES = [
  // Legitimate: a single point in time.
  { code: `export const ok1 = formatUnits(6.8);`, mustFail: false },
  { code: `export const ok2 = formatUnits(-4.61 as number);`, mustFail: false },
  { code: `export const ok3 = returnAsUnits(-0.0591);`, mustFail: false },
  { code: `export const ok4 = formatLevel(209.89);`, mustFail: false },
  { code: `export const ok5 = formatBankGrowth(100, 209.89);`, mustFail: false },
  /* Legitimate since 2026-08-03: a total on a FIXED unit value. The unit
     is worth the same money on every bet in the sum, so it adds exactly
     and means the same thing on any bankroll. See lib/units.ts. */
  { code: `export const ok6 = formatFlatUnits(asFlat(6.71));`, mustFail: false },
  // Forbidden: added while the unit's value was moving.
  { code: `export const bad1 = formatUnits(asCumulative(109.89));`, mustFail: true },
  { code: `export const bad2 = w ? formatUnits(w.pnl) : "";`, mustFail: true },
  { code: `export const bad3 = w ? formatUnits(w.yrfi.pnl) : "";`, mustFail: true },
  { code: `export const bad4 = w ? formatUnits(w.nrfi.pnl) : "";`, mustFail: true },
  { code: `export const bad5 = w ? formatUnits(w.flatPnl) : "";`, mustFail: true },
  { code: `export const bad6 = w ? formatUnits(w.yrfi.flat) : "";`, mustFail: true },
  /* A flat total is a real quantity but it is NOT a night's P&L, and the
     two are indistinguishable on screen. Routing one through the
     point-in-time formatter must stay an error so the basis is named at
     every call site. */
  { code: `export const bad7 = formatUnits(asFlat(6.71));`, mustFail: true },
  /* asFlat must not launder a compounding sum. */
  { code: `export const bad8 = formatFlatUnits(asCumulative(109.89));`, mustFail: true },
];

const HEADER = [
  `// GENERATED by scripts/check-units-guard.mjs. Deleted when it exits.`,
  `import { formatUnits, formatLevel, formatBankGrowth, returnAsUnits, asCumulative, formatFlatUnits, asFlat } from "@/lib/units";`,
  `import { replayWindow } from "@/lib/season-record";`,
  `const w = replayWindow(null, "2026-01-01", "2026-12-31");`,
];

const lines = [...HEADER, ...CASES.map((c) => c.code)];
// 1-indexed line number of each case, after the header.
const lineOf = new Map(CASES.map((c, i) => [HEADER.length + i + 1, c]));

fs.writeFileSync(probePath, lines.join("\n") + "\n", "utf8");

let raw = "";
try {
  execSync("npx tsc --noEmit", {
    cwd: projectRoot, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"],
  });
} catch (err) {
  // tsc exits non-zero when it reports errors, which is the expected
  // path here -- the probe contains deliberate ones.
  raw = `${err.stdout ?? ""}${err.stderr ?? ""}`;
} finally {
  fs.rmSync(probePath, { force: true });
}

/* Errors keyed by probe line. Anything tsc reported in ANOTHER file is
   a real problem in the codebase and is surfaced rather than swallowed
   -- this script must not become a place where unrelated type errors go
   to die. */
const probeErrors = new Set();
const foreignErrors = [];
for (const line of raw.split(/\r?\n/)) {
  const m = line.match(/^(.+?)\((\d+),\d+\): error /);
  if (!m) continue;
  if (m[1].includes("__units_guard_probe")) probeErrors.add(Number(m[2]));
  else foreignErrors.push(line);
}

const failures = [];
for (const [ln, c] of lineOf) {
  const errored = probeErrors.has(ln);
  if (c.mustFail && !errored) {
    failures.push(
      `  COMPILED BUT MUST NOT:  ${c.code}\n` +
      `    The cumulative-units guard is not working. Something widened\n` +
      `    formatUnits() in lib/units.ts, or a CumulativeUnits brand was\n` +
      `    dropped from lib/season-record.ts. A season unit total can now\n` +
      `    be rendered, which is the exact defect this guard exists for.`,
    );
  }
  if (!c.mustFail && errored) {
    failures.push(
      `  REJECTED BUT MUST NOT:  ${c.code}\n` +
      `    The guard is too tight -- it is refusing a legitimate\n` +
      `    per-night, per-bet or bank-level figure. Those are real\n` +
      `    quantities and must stay printable, or callers will route\n` +
      `    around lib/units and the brand stops protecting anything.`,
    );
  }
}

if (foreignErrors.length > 0) {
  console.error("[units-guard] type errors outside the probe:");
  for (const l of foreignErrors.slice(0, 20)) console.error("   " + l);
  process.exit(1);
}

if (failures.length > 0) {
  console.error("\n[units-guard] FAILED — the cumulative-units guard is broken:\n");
  console.error(failures.join("\n\n"));
  console.error(
    "\n  Background: 1 unit = 1% of bankroll, so units from different\n" +
    "  dates are amounts in different currencies and adding them is not\n" +
    "  money. Report bank growth (100 -> X) or a percentage return.\n" +
    "  See lib/units.ts.\n",
  );
  process.exit(1);
}

console.log(
  `[units-guard] ok — ${CASES.filter((c) => c.mustFail).length} cumulative ` +
  `forms rejected, ${CASES.filter((c) => !c.mustFail).length} point-in-time ` +
  `forms accepted.`,
);
